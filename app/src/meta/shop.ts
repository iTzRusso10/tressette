export const itemsOf = (slot: Slot) => ITEMS.filter(i => i.slot === slot);

/* ------------------------------------------------------------------ the offer of the day */

/** One item a day at a discount, the same for everybody on the same day. */
export const OFFER_DISCOUNT = 0.3;

function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** Today's offer (`day` as YYYY-MM-DD): a buyable item you don't own yet, if there is one. */
export function offerOf(day: string, owned: readonly string[]): Item | null {
  const pool = ITEMS.filter(i => i.price !== null && !owned.includes(i.id));
  if (!pool.length) return null;
  return pool[hash(day) % pool.length];
}

/** What an item costs today. */
export function priceOf(item: Item, day: string, owned: readonly string[]): number | null {
  if (item.price === null) return null;
  const offer = offerOf(day, owned);
  return offer?.id === item.id ? Math.round((item.price * (1 - OFFER_DISCOUNT)) / 10) * 10 : item.price;
}

export type BuyResult = { ok: true; coins: number; owned: string[] } | { ok: false; why: 'unknown' | 'notForSale' | 'owned' | 'coins' };

/** Buys an item: checks it's for sale, not owned, and affordable. */
export function buy(id: string, coins: number, owned: readonly string[], day: string): BuyResult {
  const item = itemById(id);
  if (!item) return { ok: false, why: 'unknown' };
  if (owned.includes(id)) return { ok: false, why: 'owned' };
  const price = priceOf(item, day, owned);
  if (price === null) return { ok: false, why: 'notForSale' };
  if (coins < price) return { ok: false, why: 'coins' };
  return { ok: true, coins: coins - price, owned: [...owned, id] };
}

/** Only owned items of the right slot can be used. */
export function canEquip(id: string, slot: Slot, owned: readonly string[]): boolean {
  const item = itemById(id);
  return !!item && item.slot === slot && (owned.includes(id) || STARTER_ITEMS.includes(id));
}
