// What a player can own and use: the felt of the table, a design drawn on it, the back of the cards.
// Pure data and functions, shared with the server (supabase/functions/progress), which checks prices.
//
// Some items are bought with coins in the shop; the felts of the arenas are won by reaching the arena.

export type Slot = 'felt' | 'pattern' | 'back';

export type Rarity = 'comune' | 'raro' | 'epico' | 'leggendario';

/** How a felt looks: the cloth (light from above → edge) and the rim around it. */
export interface FeltLook {
  /** Cloth: center light, middle, edge. */
  cloth: [string, string, string];
  /** Rim: three stops of a diagonal gradient (top left → bottom right). */
  rim: [string, string, string];
  /** A thin line just inside the rim (brass, silver, gold), or none. */
  trim: string | null;
  /** Velvet has a softer, deeper sheen than felt. */
  velvet: boolean;
  /** What the rail is made of: white glass, padded leather, wood, polished metal. */
  rail: 'glass' | 'leather' | 'wood' | 'metal';
  /** Ornaments on the rail: metal corners, studs all around. The rarer felts have more. */
  corners?: boolean;
  studs?: boolean;
}

/** How a card back looks: generated by scripts/make-art.mjs into assets/backs/<id>.png. */
export interface BackLook {
  /** Ground, darker ground, ornament, ornament highlight. */
  colors: [string, string, string, string];
  /** The motif drawn by make-art (see there). */
  motif: 'maiolica' | 'righe' | 'stelle' | 'limoni' | 'vesuvio' | 'onde' | 'corona' | 'sole' | 'tarocco';
}

interface Base {
  id: string;
  name: string;
  desc: string;
  rarity: Rarity;
  /** Coins in the shop; null when it can't be bought (won in an arena, or the default). */
  price: number | null;
}

export type Item = (Base & { slot: 'felt'; look: FeltLook }) | (Base & { slot: 'pattern' }) | (Base & { slot: 'back'; look: BackLook });

export type FeltItem = Extract<Item, { slot: 'felt' }>;
export type BackItem = Extract<Item, { slot: 'back' }>;

